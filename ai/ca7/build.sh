#!/usr/bin/env bash
# Build the CA7 model on top of Qwen with Ollama.
#   bash ai/ca7/build.sh                       # qwen2.5:7b (default)
#   CA7_BASE=qwen2.5:14b bash ai/ca7/build.sh  # bigger base, needs more RAM
set -euo pipefail

HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
BASE="${CA7_BASE:-qwen2.5:7b}"

command -v ollama >/dev/null || { echo "Install Ollama first: https://ollama.com" >&2; exit 1; }
if grep -q '"""' "$HERE/system.md"; then echo "system.md must not contain triple quotes" >&2; exit 1; fi

cat > "$HERE/Modelfile" <<MODELFILE
# CA7 - Cerveau Analytique data model (generated by build.sh)
FROM ${BASE}

SYSTEM """
$(cat "$HERE/system.md")
"""

PARAMETER temperature 0.2
PARAMETER top_p 0.9
PARAMETER top_k 40
PARAMETER num_ctx 16384
PARAMETER repeat_penalty 1.1
PARAMETER num_predict 4096
MODELFILE

ollama pull "$BASE"
ollama create ca7 -f "$HERE/Modelfile"
echo "Done. Try: ollama run ca7 \"Summarise these sensor readings: 21.4, 21.6, 35.2, 21.5\""
